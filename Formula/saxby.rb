# Template. The release workflow fills in 0.9.7 and the
# @SHA256_*@ checksums and attaches the result to the release, so
# this file is never edited by hand per release.
#
# Keeps a service block, as Homebrew formulae do. `brew services` and
# `saxby service install` are two supervisors for one port; running
# both is user error, and the second one to start says so loudly.
#
# No `version` line: brew reads the version from the download URLs,
# and `brew audit --strict` flags one that repeats it.
class Saxby < Formula
  BASE = "https://github.com/saxby-tools/saxby/releases/download".freeze

  desc "Local-first LLM routing daemon"
  homepage "https://github.com/saxby-tools/saxby"
  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
      url "#{BASE}/v0.9.7/saxby-0.9.7-darwin-arm64.tar.gz"
      sha256 "fa95f049aaf56b8c6199de005855d2f22e53898c15f7f9a078e8a47de70c9de9"
    end

    on_intel do
      url "#{BASE}/v0.9.7/saxby-0.9.7-darwin-x64.tar.gz"
      sha256 "4c49b34d1e0c6a2cddacaf08f727a865a92b4bbe0f5691a023bd6d326715b5ac"
    end
  end

  on_linux do
    on_arm do
      url "#{BASE}/v0.9.7/saxby-0.9.7-linux-arm64.tar.gz"
      sha256 "9223739cc3135bc6e78ddeeccf1f225083a889160f2c68300c57d8017f1edafc"
    end

    on_intel do
      url "#{BASE}/v0.9.7/saxby-0.9.7-linux-x64.tar.gz"
      sha256 "e38cf7caa3576b6d1e8e3bf425648884afa9452dda4c9c8c78349b7ef02b329d"
    end
  end

  def install
    bin.install "saxbyd", "saxby"

    # Generated by scripts/build.js and shipped in the tarball, so
    # every package installs the same files.
    bash_completion.install "completions/saxby.bash" => "saxby"
    zsh_completion.install "completions/_saxby"
    fish_completion.install "completions/saxby.fish"
  end

  service do
    run [opt_bin/"saxbyd"]
    keep_alive true
    log_path var/"log/saxby.log"
    error_log_path var/"log/saxby.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/saxby --version")
  end
end
